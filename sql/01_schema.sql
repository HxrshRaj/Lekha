/* ---- staging: raw, all-string, no constraints (like a flat-file landing zone) ---- */
CREATE TABLE stg.KNA1 (SEQ INT PRIMARY KEY, KUNNR NVARCHAR(40), NAME1 NVARCHAR(100), LAND1 NVARCHAR(40), REGION NVARCHAR(40), WAERS NVARCHAR(40), ZTERM_DAYS NVARCHAR(40), CREDIT_LIMIT NVARCHAR(40));
CREATE TABLE stg.LFA1 (SEQ INT PRIMARY KEY, LIFNR NVARCHAR(40), NAME1 NVARCHAR(100), LAND1 NVARCHAR(40), ZTERM_DAYS NVARCHAR(40));
CREATE TABLE stg.MARA (SEQ INT PRIMARY KEY, MATNR NVARCHAR(40), MAKTX NVARCHAR(100), MTART NVARCHAR(40), BASE_MATNR NVARCHAR(40), CONF_CODE NVARCHAR(100), STD_COST NVARCHAR(40), PRICE NVARCHAR(40), LEAD_DAYS NVARCHAR(40));
CREATE TABLE stg.VBAK (SEQ INT PRIMARY KEY, VBELN NVARCHAR(40), KUNNR NVARCHAR(40), AUDAT NVARCHAR(40), VDATU NVARCHAR(40), WAERK NVARCHAR(40), NETWR NVARCHAR(40));
CREATE TABLE stg.VBAP (SEQ INT PRIMARY KEY, VBELN NVARCHAR(40), POSNR NVARCHAR(40), MATNR NVARCHAR(40), KWMENG NVARCHAR(40), NETPR NVARCHAR(40), NETWR NVARCHAR(40));
CREATE TABLE stg.LIKP (SEQ INT PRIMARY KEY, VBELN_VL NVARCHAR(40), VBELN NVARCHAR(40), LFDAT NVARCHAR(40), WADAT_IST NVARCHAR(40));
CREATE TABLE stg.LIPS (SEQ INT PRIMARY KEY, VBELN_VL NVARCHAR(40), POSNR NVARCHAR(40), MATNR NVARCHAR(40), LFIMG NVARCHAR(40));
CREATE TABLE stg.VBRK (SEQ INT PRIMARY KEY, VBELN_VF NVARCHAR(40), VBELN NVARCHAR(40), KUNNR NVARCHAR(40), FKDAT NVARCHAR(40), FAEDT NVARCHAR(40), NETWR NVARCHAR(40), WAERK NVARCHAR(40));
CREATE TABLE stg.BSAD (SEQ INT PRIMARY KEY, VBELN_VF NVARCHAR(40), AUGDT NVARCHAR(40), DMBTR NVARCHAR(40), WAERS NVARCHAR(40));
CREATE TABLE stg.EKKO (SEQ INT PRIMARY KEY, EBELN NVARCHAR(40), LIFNR NVARCHAR(40), BEDAT NVARCHAR(40), WAERS NVARCHAR(40));
CREATE TABLE stg.EKPO (SEQ INT PRIMARY KEY, EBELN NVARCHAR(40), EBELP NVARCHAR(40), MATNR NVARCHAR(40), MENGE NVARCHAR(40), NETPR NVARCHAR(40));
CREATE TABLE stg.EKBE (SEQ INT PRIMARY KEY, EBELN NVARCHAR(40), EBELP NVARCHAR(40), BUDAT NVARCHAR(40), MENGE NVARCHAR(40));
CREATE TABLE stg.RBKP (SEQ INT PRIMARY KEY, BELNR_MM NVARCHAR(40), EBELN NVARCHAR(40), LIFNR NVARCHAR(40), BLDAT NVARCHAR(40), FAEDT NVARCHAR(40), RMWWR NVARCHAR(40), AUGDT NVARCHAR(40), WAERS NVARCHAR(40));

/* ---- core: typed, keyed, constrained ---- */
CREATE TABLE dbo.KNA1 (KUNNR VARCHAR(10) NOT NULL PRIMARY KEY, NAME1 NVARCHAR(100) NOT NULL, LAND1 CHAR(2) NULL, REGION VARCHAR(4) NULL,
    WAERS CHAR(3) NOT NULL, ZTERM_DAYS INT NULL, CREDIT_LIMIT DECIMAL(15,2) NULL);
CREATE TABLE dbo.LFA1 (LIFNR VARCHAR(10) NOT NULL PRIMARY KEY, NAME1 NVARCHAR(100) NOT NULL, LAND1 CHAR(2) NULL, ZTERM_DAYS INT NULL);
CREATE TABLE dbo.MARA (MATNR VARCHAR(20) NOT NULL PRIMARY KEY, MAKTX NVARCHAR(100) NOT NULL, MTART CHAR(4) NULL,
    BASE_MATNR VARCHAR(20) NULL, CONF_CODE VARCHAR(60) NULL, STD_COST DECIMAL(15,2) NULL, PRICE DECIMAL(15,2) NOT NULL CHECK (PRICE >= 0), LEAD_DAYS INT NULL);
CREATE TABLE dbo.CSKS (KOSTL VARCHAR(6) NOT NULL PRIMARY KEY, KTEXT NVARCHAR(60), ABTEI VARCHAR(20));
CREATE TABLE dbo.SKA1 (HKONT INT NOT NULL PRIMARY KEY, TXT NVARCHAR(60) NOT NULL, GRP VARCHAR(5) NOT NULL);

CREATE TABLE dbo.VBAK (VBELN VARCHAR(10) NOT NULL PRIMARY KEY, KUNNR VARCHAR(10) NOT NULL REFERENCES dbo.KNA1 (KUNNR),
    AUDAT DATE NOT NULL, VDATU DATE NOT NULL, WAERK CHAR(3) NOT NULL, NETWR DECIMAL(15,2) NOT NULL CHECK (NETWR >= 0));
CREATE TABLE dbo.VBAP (VBELN VARCHAR(10) NOT NULL REFERENCES dbo.VBAK (VBELN), POSNR INT NOT NULL, MATNR VARCHAR(20) NOT NULL REFERENCES dbo.MARA (MATNR),
    KWMENG INT NOT NULL CHECK (KWMENG > 0), NETPR DECIMAL(15,2) NOT NULL CHECK (NETPR >= 0), NETWR DECIMAL(15,2) NULL, PRIMARY KEY (VBELN, POSNR));
CREATE TABLE dbo.LIKP (VBELN_VL VARCHAR(10) NOT NULL PRIMARY KEY, VBELN VARCHAR(10) NOT NULL REFERENCES dbo.VBAK (VBELN), LFDAT DATE NOT NULL, WADAT_IST DATE NOT NULL);
CREATE TABLE dbo.LIPS (VBELN_VL VARCHAR(10) NOT NULL REFERENCES dbo.LIKP (VBELN_VL), POSNR INT NOT NULL, MATNR VARCHAR(20) NOT NULL REFERENCES dbo.MARA (MATNR),
    LFIMG INT NOT NULL CHECK (LFIMG >= 0), PRIMARY KEY (VBELN_VL, POSNR));
CREATE TABLE dbo.VBRK (VBELN_VF VARCHAR(10) NOT NULL PRIMARY KEY, VBELN VARCHAR(10) NOT NULL REFERENCES dbo.VBAK (VBELN),
    KUNNR VARCHAR(10) NOT NULL REFERENCES dbo.KNA1 (KUNNR), FKDAT DATE NOT NULL, FAEDT DATE NOT NULL,
    NETWR DECIMAL(15,2) NOT NULL CHECK (NETWR >= 0), WAERK CHAR(3) NOT NULL);
CREATE TABLE dbo.BSAD (VBELN_VF VARCHAR(10) NOT NULL PRIMARY KEY REFERENCES dbo.VBRK (VBELN_VF), AUGDT DATE NOT NULL,
    DMBTR DECIMAL(15,2) NOT NULL CHECK (DMBTR >= 0), WAERS CHAR(3) NULL);

CREATE TABLE dbo.EKKO (EBELN VARCHAR(10) NOT NULL PRIMARY KEY, LIFNR VARCHAR(10) NOT NULL REFERENCES dbo.LFA1 (LIFNR), BEDAT DATE NOT NULL, WAERS CHAR(3) NULL);
CREATE TABLE dbo.EKPO (EBELN VARCHAR(10) NOT NULL REFERENCES dbo.EKKO (EBELN), EBELP INT NOT NULL, MATNR VARCHAR(20) NOT NULL REFERENCES dbo.MARA (MATNR),
    MENGE INT NOT NULL CHECK (MENGE > 0), NETPR DECIMAL(15,2) NOT NULL CHECK (NETPR >= 0), PRIMARY KEY (EBELN, EBELP));
CREATE TABLE dbo.EKBE (EBELN VARCHAR(10) NOT NULL, EBELP INT NOT NULL, BUDAT DATE NOT NULL, MENGE INT NOT NULL CHECK (MENGE >= 0),
    PRIMARY KEY (EBELN, EBELP), FOREIGN KEY (EBELN, EBELP) REFERENCES dbo.EKPO (EBELN, EBELP));
CREATE TABLE dbo.RBKP (BELNR_MM VARCHAR(10) NOT NULL PRIMARY KEY, EBELN VARCHAR(10) NOT NULL, LIFNR VARCHAR(10) NOT NULL REFERENCES dbo.LFA1 (LIFNR),
    BLDAT DATE NOT NULL, FAEDT DATE NOT NULL, RMWWR DECIMAL(15,2) NOT NULL CHECK (RMWWR >= 0), AUGDT DATE NULL, WAERS CHAR(3) NULL);

CREATE TABLE dbo.BKPF (BELNR VARCHAR(10) NOT NULL PRIMARY KEY, BUDAT DATE NOT NULL, GJAHR INT NOT NULL, MONAT INT NOT NULL, BLART CHAR(2) NOT NULL, XBLNR VARCHAR(20) NULL);
CREATE TABLE dbo.BSEG (BELNR VARCHAR(10) NOT NULL REFERENCES dbo.BKPF (BELNR), BUZEI INT NOT NULL, HKONT INT NOT NULL REFERENCES dbo.SKA1 (HKONT),
    KOSTL VARCHAR(6) NULL REFERENCES dbo.CSKS (KOSTL), SHKZG CHAR(1) NOT NULL CHECK (SHKZG IN ('S','H')), DMBTR DECIMAL(15,2) NOT NULL, PERIOD INT NOT NULL,
    PRIMARY KEY (BELNR, BUZEI));
CREATE TABLE dbo.BUDG (KOSTL VARCHAR(6) NOT NULL REFERENCES dbo.CSKS (KOSTL), PERIOD INT NOT NULL, AMT_BUDGET DECIMAL(15,2) NOT NULL, PRIMARY KEY (KOSTL, PERIOD));
CREATE TABLE dbo.TICKETS (TICKET_ID VARCHAR(10) NOT NULL PRIMARY KEY, VBELN_VF VARCHAR(10) NULL, CREATED DATE NOT NULL, DESCRIPTION NVARCHAR(500) NOT NULL, CATEGORY VARCHAR(30) NOT NULL);

/* quarantine: every rejected staging row with the reason and the raw row as JSON */
CREATE TABLE dbo.Quarantine (QID INT IDENTITY PRIMARY KEY, SRC_TABLE VARCHAR(10) NOT NULL, SRC_SEQ INT NOT NULL, REASON VARCHAR(30) NOT NULL,
    RAW_ROW NVARCHAR(MAX) NULL, QUARANTINED_AT DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME());

/* ---- indexes that the views rely on ---- */
CREATE INDEX IX_VBAK_KUNNR ON dbo.VBAK (KUNNR) INCLUDE (AUDAT);
CREATE INDEX IX_VBRK_FKDAT ON dbo.VBRK (FKDAT) INCLUDE (NETWR, KUNNR, FAEDT, VBELN);
CREATE INDEX IX_VBRK_VBELN ON dbo.VBRK (VBELN);
CREATE INDEX IX_BSAD_AUGDT ON dbo.BSAD (AUGDT) INCLUDE (DMBTR);
CREATE INDEX IX_LIKP_VBELN ON dbo.LIKP (VBELN) INCLUDE (WADAT_IST, LFDAT);
CREATE INDEX IX_EKPO_MATNR ON dbo.EKPO (MATNR);
CREATE INDEX IX_Quarantine_Src ON dbo.Quarantine (SRC_TABLE, REASON);
GO
