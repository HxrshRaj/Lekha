    dbo.LIPS, dbo.LIKP, dbo.VBAP, dbo.VBAK, dbo.CSKS, dbo.SKA1, dbo.MARA, dbo.LFA1, dbo.KNA1, dbo.Quarantine, dbo.Params;
DROP TABLE IF EXISTS stg.KNA1, stg.LFA1, stg.MARA, stg.VBAK, stg.VBAP, stg.LIKP, stg.LIPS, stg.VBRK, stg.BSAD, stg.EKKO, stg.EKPO, stg.EKBE, stg.RBKP;
