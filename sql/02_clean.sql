/* Cleaning step: staging (stg.*) -> core (dbo.*) or dbo.Quarantine.
   Reason priority per row (first match wins):
   NULL_REQUIRED > DUPLICATE_KEY > BAD_DATE > NEGATIVE_AMOUNT > CURRENCY_MISMATCH > ORPHAN_KEY
   Each procedure builds #r (SEQ, REASON) once, then splits staging rows in two. Mirrors lekha/staging.py. */
USE lekha;
GO
/* ---------------- master data: MERGE (upsert + remove vanished rows) ---------------- */
CREATE OR ALTER PROCEDURE dbo.usp_Clean_KNA1 AS
BEGIN
    SET NOCOUNT ON;
    DROP TABLE IF EXISTS #r;
    ;WITH c AS (
        SELECT s.SEQ, s.KUNNR,
               CASE WHEN NULLIF(LTRIM(RTRIM(s.KUNNR)),'') IS NULL OR NULLIF(LTRIM(RTRIM(s.NAME1)),'') IS NULL OR NULLIF(LTRIM(RTRIM(s.WAERS)),'') IS NULL THEN 1 ELSE 0 END AS req_null
        FROM stg.KNA1 s), d AS (
        SELECT c.*, ROW_NUMBER() OVER (PARTITION BY req_null, KUNNR ORDER BY SEQ) AS rn FROM c)
    SELECT SEQ, CASE WHEN req_null = 1 THEN 'NULL_REQUIRED' WHEN rn > 1 THEN 'DUPLICATE_KEY' END AS REASON INTO #r FROM d;
    INSERT dbo.Quarantine (SRC_TABLE, SRC_SEQ, REASON, RAW_ROW)
    SELECT 'KNA1', r.SEQ, r.REASON, (SELECT s.* FOR JSON PATH, WITHOUT_ARRAY_WRAPPER) FROM #r r JOIN stg.KNA1 s ON s.SEQ = r.SEQ WHERE r.REASON IS NOT NULL;
    MERGE dbo.KNA1 AS t
    USING (SELECT s.* FROM stg.KNA1 s JOIN #r r ON r.SEQ = s.SEQ WHERE r.REASON IS NULL) AS s ON t.KUNNR = s.KUNNR
    WHEN MATCHED THEN UPDATE SET NAME1 = s.NAME1, LAND1 = s.LAND1, REGION = s.REGION, WAERS = s.WAERS,
         ZTERM_DAYS = CONVERT(INT, s.ZTERM_DAYS), CREDIT_LIMIT = CONVERT(DECIMAL(15,2), s.CREDIT_LIMIT)
    WHEN NOT MATCHED BY TARGET THEN INSERT (KUNNR, NAME1, LAND1, REGION, WAERS, ZTERM_DAYS, CREDIT_LIMIT)
         VALUES (s.KUNNR, s.NAME1, s.LAND1, s.REGION, s.WAERS, CONVERT(INT, s.ZTERM_DAYS), CONVERT(DECIMAL(15,2), s.CREDIT_LIMIT))
    WHEN NOT MATCHED BY SOURCE THEN DELETE;
END
GO
