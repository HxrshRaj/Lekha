CREATE OR ALTER PROCEDURE dbo.usp_CleanAll AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRAN;
    DELETE dbo.Quarantine;
    -- children first so the FK constraints allow the delete
    DELETE dbo.RBKP; DELETE dbo.EKBE; DELETE dbo.EKPO; DELETE dbo.EKKO; DELETE dbo.BSAD; DELETE dbo.VBRK;
    DELETE dbo.LIPS; DELETE dbo.LIKP; DELETE dbo.VBAP; DELETE dbo.VBAK;
    EXEC dbo.usp_Clean_KNA1; EXEC dbo.usp_Clean_LFA1; EXEC dbo.usp_Clean_MARA;
    EXEC dbo.usp_Clean_VBAK; EXEC dbo.usp_Clean_VBAP; EXEC dbo.usp_Clean_LIKP; EXEC dbo.usp_Clean_LIPS;
    EXEC dbo.usp_Clean_VBRK; EXEC dbo.usp_Clean_BSAD;
    EXEC dbo.usp_Clean_EKKO; EXEC dbo.usp_Clean_EKPO; EXEC dbo.usp_Clean_EKBE; EXEC dbo.usp_Clean_RBKP;
    COMMIT;
END
GO
