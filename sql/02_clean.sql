CREATE OR ALTER PROCEDURE dbo.usp_Clean_VBAK AS
BEGIN
    SET NOCOUNT ON;
    DROP TABLE IF EXISTS #r;
    ;WITH c AS (
        SELECT s.*, k.WAERS AS cust_cur, k.KUNNR AS cust_key,
               CASE WHEN NULLIF(LTRIM(RTRIM(s.VBELN)),'') IS NULL OR NULLIF(LTRIM(RTRIM(s.KUNNR)),'') IS NULL OR NULLIF(LTRIM(RTRIM(s.AUDAT)),'') IS NULL
                      OR NULLIF(LTRIM(RTRIM(s.VDATU)),'') IS NULL OR NULLIF(LTRIM(RTRIM(s.NETWR)),'') IS NULL OR NULLIF(LTRIM(RTRIM(s.WAERK)),'') IS NULL THEN 1 ELSE 0 END AS req_null
        FROM stg.VBAK s LEFT JOIN dbo.KNA1 k ON k.KUNNR = s.KUNNR), d AS (
        SELECT c.*, ROW_NUMBER() OVER (PARTITION BY req_null, VBELN ORDER BY SEQ) AS rn FROM c)
    SELECT SEQ, CASE WHEN req_null = 1 THEN 'NULL_REQUIRED' WHEN rn > 1 THEN 'DUPLICATE_KEY'
                     WHEN TRY_CONVERT(DATE, AUDAT, 23) IS NULL OR TRY_CONVERT(DATE, VDATU, 23) IS NULL THEN 'BAD_DATE'
                     WHEN TRY_CONVERT(DECIMAL(15,2), NETWR) < 0 THEN 'NEGATIVE_AMOUNT'
                     WHEN cust_cur IS NOT NULL AND WAERK <> cust_cur THEN 'CURRENCY_MISMATCH'
                     WHEN cust_key IS NULL THEN 'ORPHAN_KEY' END AS REASON INTO #r FROM d;
    INSERT dbo.Quarantine (SRC_TABLE, SRC_SEQ, REASON, RAW_ROW)
    SELECT 'VBAK', r.SEQ, r.REASON, (SELECT s.* FOR JSON PATH, WITHOUT_ARRAY_WRAPPER) FROM #r r JOIN stg.VBAK s ON s.SEQ = r.SEQ WHERE r.REASON IS NOT NULL;
    INSERT dbo.VBAK (VBELN, KUNNR, AUDAT, VDATU, WAERK, NETWR)
    SELECT s.VBELN, s.KUNNR, CONVERT(DATE, s.AUDAT, 23), CONVERT(DATE, s.VDATU, 23), s.WAERK, CONVERT(DECIMAL(15,2), s.NETWR)
    FROM stg.VBAK s JOIN #r r ON r.SEQ = s.SEQ WHERE r.REASON IS NULL;
END
