"""FastAPI service. Serves PRECOMPUTED results (results/results.json from lekha.pipeline), so the deployed demo needs
no SQL Server. All data is SYNTHETIC and SAP-STYLE (simplified); nothing is connected to a real SAP system."""
from __future__ import annotations

import json
import os
from functools import lru_cache
from pathlib import Path

from fastapi import FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from . import nlp
from .excel import build_workbook

ROOT = Path(__file__).resolve().parents[1]
RESULTS = Path(os.environ.get("LEKHA_RESULTS", ROOT / "results"))
STATIC = Path(os.environ.get("LEKHA_STATIC", ROOT / "static"))
DISCLAIMER = "SYNTHETIC, SAP-STYLE (simplified) data generated by Lekha. Not real SAP data and not connected to any SAP system."

app = FastAPI(
    title="Lekha API",
    description=f"Finance and order-to-cash analytics. **{DISCLAIMER}** Results are precomputed by the Python pipeline "
                "(the T-SQL layer is verified separately against the same KPIs).",
    version="1.0.0")
app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["GET", "POST"], allow_headers=["*"])


@lru_cache(maxsize=1)
def results() -> dict:
    f = RESULTS / "results.json"
    if not f.exists():
        raise HTTPException(503, "results.json missing - run `python -m lekha.pipeline`")
    return json.loads(f.read_text(encoding="utf-8"))


def _get(key: str):
    r = results()
    if key not in r:
        raise HTTPException(404, f"no such result: {key}")
    return r[key]


@app.get("/api/health", tags=["meta"])
def health():
    return {"status": "ok", "disclaimer": DISCLAIMER, "results_loaded": (RESULTS / "results.json").exists()}


@app.get("/api/meta", tags=["meta"])
def meta():
    return {**results()["meta"], "disclaimer": DISCLAIMER}


@app.get("/api/kpis", tags=["kpis"])
def kpis():
    return _get("kpis")


@app.get("/api/aging", tags=["kpis"])
def aging():
    return {"receivables": _get("ar_aging"), "receivables_by_region": _get("ar_aging_by_region"), "payables": _get("ap_aging")}


@app.get("/api/dso", tags=["kpis"])
def dso():
    return _get("dso")


@app.get("/api/otif", tags=["kpis"])
def otif():
    return _get("otif")


@app.get("/api/cycle-time", tags=["kpis"])
def cycle_time():
    return _get("cycle_time")


@app.get("/api/variance", tags=["finance"])
def variance(period: int | None = Query(None, description="YYYYMM; default = latest"), kostl: str | None = None):
    rows = _get("variance")
    if period is None:
        period = max(r["PERIOD"] for r in rows)
    rows = [r for r in rows if r["PERIOD"] == period and (kostl is None or r["KOSTL"] == kostl)]
    return {"period": period, "rows": sorted(rows, key=lambda r: -abs(r["Variance"]))}


