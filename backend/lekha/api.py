def pnl():
    return _get("pnl")


@app.get("/api/forecast", tags=["analytics"])
def forecast():
    return _get("forecast")


@app.get("/api/regression", tags=["analytics"])
def regression():
    return _get("regression")


@app.get("/api/simulation", tags=["analytics"])
def simulation():
    return _get("simulation")


@app.get("/api/nlp/metrics", tags=["nlp"])
def nlp_metrics():
    return _get("nlp")


class Text(BaseModel):
    text: str = Field(min_length=3, max_length=2000, examples=["we were billed twice for the same order, please cancel the duplicate"])


@app.post("/api/nlp/classify", tags=["nlp"])
def classify(body: Text):
    m = RESULTS / "nlp_model.joblib"
    if not m.exists():
        raise HTTPException(503, "nlp model missing")
    return {**nlp.classify(str(m), body.text), "note": "Classifier trained on SYNTHETIC template-generated text."}


@app.get("/api/anomalies", tags=["analytics"])
def anomalies(kind: str = Query("invoices", pattern="^(invoices|payments)$"), limit: int = Query(50, ge=1, le=200)):
    a = _get("anomaly")
    return {"summary": a[kind], "items": a["invoice_list" if kind == "invoices" else "payment_list"][:limit]}


@app.get("/api/data-quality", tags=["data quality"])
def data_quality():
    return _get("data_quality")


@app.get("/export.xlsx", tags=["export"], response_class=FileResponse)
def export_xlsx():
    out = RESULTS / "lekha_export.xlsx"
    if not out.exists():
        build_workbook(RESULTS, out)
    return FileResponse(out, filename="lekha_export.xlsx",
                        media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")


if STATIC.exists():  # single-service deploy: serve the built React app next to the API
    app.mount("/assets", StaticFiles(directory=STATIC / "assets"), name="assets")

    @app.get("/{path:path}", include_in_schema=False)
    def spa(path: str):
        f = STATIC / path
        return FileResponse(f if path and f.is_file() else STATIC / "index.html")
