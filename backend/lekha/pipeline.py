"""End-to-end pipeline: generate -> stage -> clean (pandas reference) -> KPIs -> analytics -> results/ (JSON + Parquet).

    python -m lekha.pipeline [--scale 1.0] [--seed 42] [--out results]
The deployed API serves only these precomputed files (no SQL Server needed at runtime).
"""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd

from . import anomaly, forecast, kpis, nlp, regression, simulation
from .staging import REASONS, STAGED
from .tables import AS_OF, build, incomplete_orders

ROOT = Path(__file__).resolve().parents[1]


def _clean(o):
    if isinstance(o, dict):
        return {str(k): _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating, float)):
        return None if (isinstance(o, float) and not np.isfinite(o)) or (isinstance(o, np.floating) and not np.isfinite(o)) else float(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if isinstance(o, (pd.Timestamp, np.datetime64)):
        return str(pd.Timestamp(o).date())
    if isinstance(o, pd.DataFrame):
        o = o.copy()
        for c in o.columns:
            if pd.api.types.is_datetime64_any_dtype(o[c]):
                o[c] = o[c].dt.strftime("%Y-%m-%d")
        return _clean(json.loads(o.to_json(orient="records")))
    return o


def dq_summary(stg, quarantine, log) -> dict:
    rows = []
    for t in STAGED:
        n = len(stg[t])
        q = quarantine[quarantine.SRC_TABLE == t]
        rows.append({"table": t, "staging_rows": n, "quarantined": int(len(q)), "quarantine_pct": round(100 * len(q) / n, 2),
                     **{r: int((q.REASON == r).sum()) for r in REASONS}})
    inj = log.groupby("DEFECT").size().to_dict()
    total = sum(r["staging_rows"] for r in rows)
    qtot = int(len(quarantine))
    return {"tables": rows, "total_staging_rows": total, "total_quarantined": qtot, "quarantine_pct": round(100 * qtot / total, 2),
            "by_reason": {r: int((quarantine.REASON == r).sum()) for r in REASONS}, "injected_defects": {k: int(v) for k, v in inj.items()},
            "injected_total": int(len(log)), "injected_pct": round(100 * len(log) / total, 2),
            "note": "Defects are injected at ~2% per table; quarantine % is higher because rows whose parent was rejected "
                    "are rejected too (ORPHAN_KEY cascade)."}


def run(seed: int = 42, scale: float = 1.0, out: str | Path = ROOT / "results", sim_runs: int = 5000, quick: bool = False) -> dict:
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    t, truth, stg, quarantine, log = build(seed, scale)
    res: dict = {"meta": {
        "disclaimer": "SYNTHETIC, SAP-STYLE (simplified) data generated by Lekha. Not real SAP data, no SAP connection.",
        "seed": seed, "scale": scale, "as_of": str(AS_OF.date()),
        "rows": {k: int(len(v)) for k, v in truth.items() if k != "TRUTH_ANOMALY"},
        "total_rows_core_truth": int(sum(len(v) for k, v in truth.items() if k != "TRUTH_ANOMALY"))}}
    res["data_quality"] = dq_summary(stg, quarantine, log)
    res["kpis"] = kpis.headline(t, AS_OF)
    res["ar_aging"] = kpis.ar_aging(t, AS_OF)
    res["ap_aging"] = kpis.ap_aging(t, AS_OF)
    res["dso"] = kpis.dso_monthly(t)
    res["otif"] = kpis.otif_monthly(t)
    res["cycle_time"] = kpis.cycle_monthly(t)
    bv = kpis.budget_variance(t)
    res["variance"] = bv
    res["pnl"] = kpis.pnl_period(t)
    res["ar_aging_by_region"] = kpis.ar_open(t, AS_OF).pivot_table(index="REGION", columns="Bucket", values="NETWR", aggfunc="sum", fill_value=0).reindex(columns=kpis.BUCKETS, fill_value=0).reset_index()
    res["regression"] = regression.run(t, seed)

    ws = forecast.weekly_series(t)
    fc = {}
    for name, s in ws.items():
        bt = forecast.backtest(s)
        best = bt["best"]
        fut = forecast.future(s, best, 13)
        fc[name] = {"backtest": bt, "history": pd.DataFrame({"week_end": s.index[-52:], "actual": s.to_numpy()[-52:]}),
                    "forecast_model": best, "forecast": fut}
    res["forecast"] = fc

    cash = simulation.cash_collection(t, AS_OF, runs=sim_runs)
    res["simulation"] = {"cash_collection": cash, "safety_stock": simulation.safety_stock(t, AS_OF, runs=20000 if not quick else 4000)}
    res["nlp"] = nlp.train(t["TICKETS"], seed, str(out / "nlp_model.joblib"))
    tr = truth["TRUTH_ANOMALY"]
    inv_a = anomaly.detect_invoices(t, set(tr[tr.KIND == "invoice"].KEY), seed, skip_orders=incomplete_orders(stg, quarantine))
    pay_a = anomaly.detect_payments(t, set(tr[tr.KIND == "payment"].KEY), seed)
    res["anomaly"] = {"invoices": {k: v for k, v in inv_a.items() if k != "top"}, "payments": {k: v for k, v in pay_a.items() if k != "top"},
                      "invoice_list": inv_a["top"].head(100), "payment_list": pay_a["top"].head(50)}
    res["meta"]["runtime_seconds"] = round(time.time() - t0, 1)

    (out / "results.json").write_text(json.dumps(_clean(res), indent=1), encoding="utf-8")
    # parquet exports used by the API export + Power BI star schema
    kpis.ar_open(t, AS_OF)[["VBELN_VF", "KUNNR", "FKDAT", "FAEDT", "NETWR"]].to_parquet(out / "ar_open.parquet")
    t["VBRK"].to_parquet(out / "invoices.parquet")
    quarantine.to_parquet(out / "quarantine.parquet")
    from .excel import build_workbook
    build_workbook(out, out / "lekha_export.xlsx")
    return res


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--scale", type=float, default=1.0)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", default=str(ROOT / "results"))
    a = ap.parse_args()
    r = run(a.seed, a.scale, a.out)
    print(json.dumps(_clean(r["kpis"]), indent=1))
    print("runtime", r["meta"]["runtime_seconds"], "s")
