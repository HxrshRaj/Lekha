"""Excel workbook with real formulas (aging buckets, variance, DSO, P&L) and conditional formatting.
Values that are inputs (open invoices, actuals, budgets) are written as numbers; every derived figure is an Excel formula,
so recalculating in LibreOffice/Excel must reproduce the pipeline numbers (tests/test_excel.py checks this)."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.formatting.rule import CellIsRule, ColorScaleRule, FormulaRule
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

HDR = PatternFill("solid", fgColor="1F3A5F")
HFONT = Font(bold=True, color="FFFFFF")
RED, GREEN = PatternFill("solid", bgColor="F8CBAD", fgColor="F8CBAD"), PatternFill("solid", bgColor="C6E0B4", fgColor="C6E0B4")
DISCLAIMER = "SYNTHETIC, SAP-STYLE (simplified) data generated by Lekha. Not real SAP data; no SAP connection."


def _header(ws, row, names, widths=None):
    for i, n in enumerate(names, 1):
        c = ws.cell(row=row, column=i, value=n)
        c.fill, c.font = HDR, HFONT
        c.alignment = Alignment(horizontal="center")
        ws.column_dimensions[get_column_letter(i)].width = (widths or {}).get(i, 16)


def build_workbook(results_dir: str | Path, path: str | Path) -> Path:
    rd = Path(results_dir)
    res = json.loads((rd / "results.json").read_text(encoding="utf-8"))
    ar = pd.read_parquet(rd / "ar_open.parquet")
    wb = Workbook()

    # ---- AR_Open: inputs + formulas for days overdue and bucket ----
    ws = wb.active
    ws.title = "AR_Open"
    _header(ws, 1, ["Invoice", "Customer", "Invoice date", "Due date", "Amount", "Days overdue", "Bucket"])
    for i, r in enumerate(ar.itertuples(index=False), start=2):
        ws.cell(i, 1, r.VBELN_VF); ws.cell(i, 2, r.KUNNR)
        ws.cell(i, 3, pd.Timestamp(r.FKDAT).to_pydatetime()).number_format = "yyyy-mm-dd"
        ws.cell(i, 4, pd.Timestamp(r.FAEDT).to_pydatetime()).number_format = "yyyy-mm-dd"
        ws.cell(i, 5, float(r.NETWR)).number_format = "#,##0.00"
        ws.cell(i, 6, f"=Summary!$B$3-D{i}")
        ws.cell(i, 7, f'=IF(D{i}>Summary!$B$3,"Current",IF(F{i}<=30,"0-30",IF(F{i}<=60,"31-60",IF(F{i}<=90,"61-90","90+"))))')
    n_ar = len(ar) + 1
    ws.conditional_formatting.add(f"F2:F{n_ar}", CellIsRule(operator="greaterThan", formula=["90"], fill=RED))
    ws.freeze_panes = "A2"

    # ---- Aging summary ----
    ag = wb.create_sheet("Aging")
    _header(ag, 1, ["Bucket", "Invoices", "Amount", "% of open AR"])
    for i, b in enumerate(["Current", "0-30", "31-60", "61-90", "90+"], start=2):
        ag.cell(i, 1, b)
        ag.cell(i, 2, f"=COUNTIFS(AR_Open!$G$2:$G${n_ar},A{i})")
        ag.cell(i, 3, f"=SUMIFS(AR_Open!$E$2:$E${n_ar},AR_Open!$G$2:$G${n_ar},A{i})").number_format = "#,##0.00"
        ag.cell(i, 4, f"=IFERROR(C{i}/$C$7,0)").number_format = "0.0%"
    ag.cell(7, 1, "Total"); ag.cell(7, 2, "=SUM(B2:B6)"); ag.cell(7, 3, "=SUM(C2:C6)").number_format = "#,##0.00"; ag.cell(7, 4, "=SUM(D2:D6)").number_format = "0.0%"
    for c in "ABCD":
        ag[f"{c}7"].font = Font(bold=True)
    ag.conditional_formatting.add("C2:C6", ColorScaleRule(start_type="min", start_color="FFFFFF", end_type="max", end_color="F4B183"))
    ag.conditional_formatting.add("A6:D6", FormulaRule(formula=["$C$6>0"], fill=RED))

    # ---- DSO ----
    ds = wb.create_sheet("DSO")
    _header(ds, 1, ["Month end", "Open AR", "Credit sales (trailing 90d)", "DSO (days)"])
    for i, r in enumerate(res["dso"], start=2):
        ds.cell(i, 1, pd.Timestamp(r["MonthEnd"]).to_pydatetime()).number_format = "yyyy-mm-dd"
        ds.cell(i, 2, r["OpenAR"]).number_format = "#,##0.00"
        ds.cell(i, 3, r["Sales90"]).number_format = "#,##0.00"
        ds.cell(i, 4, f"=ROUND(B{i}/C{i}*90,2)")
    n_dso = len(res["dso"]) + 1
    ds.conditional_formatting.add(f"D2:D{n_dso}", ColorScaleRule(start_type="min", start_color="C6E0B4", end_type="max", end_color="F8CBAD"))

    # ---- Variance (last 12 periods) ----
    va = wb.create_sheet("Variance")
    _header(va, 1, ["Cost centre", "Period", "Actual", "Budget", "Variance", "Variance %"])
    v = pd.DataFrame(res["variance"])
    v = v[v["PERIOD"] >= sorted(v["PERIOD"].unique())[-12]].sort_values(["KOSTL", "PERIOD"])
    for i, r in enumerate(v.itertuples(index=False), start=2):
        va.cell(i, 1, r.KOSTL); va.cell(i, 2, int(r.PERIOD))
        va.cell(i, 3, float(r.Actual)).number_format = "#,##0.00"
        va.cell(i, 4, float(r.Budget)).number_format = "#,##0.00"
        va.cell(i, 5, f"=C{i}-D{i}").number_format = "#,##0.00"
        va.cell(i, 6, f"=IFERROR(E{i}/D{i},0)").number_format = "0.0%"
    n_va = len(v) + 1
    va.conditional_formatting.add(f"F2:F{n_va}", CellIsRule(operator="greaterThan", formula=["0.1"], fill=RED))
    va.conditional_formatting.add(f"F2:F{n_va}", CellIsRule(operator="lessThan", formula=["-0.1"], fill=GREEN))
    va.freeze_panes = "A2"

    # ---- P&L ----
    pl = wb.create_sheet("PnL")
    _header(pl, 1, ["Period", "Revenue", "COGS", "Opex", "Gross profit", "EBIT", "Gross margin %"])
    for i, r in enumerate(res["pnl"], start=2):
        pl.cell(i, 1, int(r["PERIOD"]))
        for j, k in enumerate(["Revenue", "Cogs", "Opex"], start=2):
            pl.cell(i, j, r[k]).number_format = "#,##0.00"
        pl.cell(i, 5, f"=B{i}-C{i}").number_format = "#,##0.00"
        pl.cell(i, 6, f"=E{i}-D{i}").number_format = "#,##0.00"
        pl.cell(i, 7, f"=IFERROR(E{i}/B{i},0)").number_format = "0.0%"
    n_pl = len(res["pnl"]) + 1
    pl.conditional_formatting.add(f"F2:F{n_pl}", CellIsRule(operator="lessThan", formula=["0"], fill=RED))

    # ---- Summary (first sheet) ----
    sm = wb.create_sheet("Summary", 0)
    sm["A1"] = "Lekha - finance & order-to-cash summary"; sm["A1"].font = Font(bold=True, size=14)
    sm["A2"] = DISCLAIMER; sm["A2"].font = Font(italic=True, color="C00000")
    sm["A3"] = "As-of date"; sm["B3"] = pd.Timestamp(res["meta"]["as_of"]).to_pydatetime(); sm["B3"].number_format = "yyyy-mm-dd"
    rows = [("Open receivables", "=Aging!C7", "#,##0.00"),
            ("Overdue 90+ days", "=Aging!C6", "#,##0.00"),
            ("Overdue 90+ share of open AR", "=IFERROR(Aging!C6/Aging!C7,0)", "0.0%"),
            ("DSO - latest month (days)", f"=DSO!D{n_dso}", "0.00"),
            ("Total budget variance, last 12 periods", f"=SUM(Variance!E2:E{n_va})", "#,##0.00"),
            ("Revenue, last 12 periods", f"=SUM(PnL!B{n_pl - 11}:B{n_pl})", "#,##0.00"),
            ("EBIT, last 12 periods", f"=SUM(PnL!F{n_pl - 11}:F{n_pl})", "#,##0.00")]
    for i, (label, f, fmt) in enumerate(rows, start=5):
        sm.cell(i, 1, label); c = sm.cell(i, 2, f); c.number_format = fmt
    sm.column_dimensions["A"].width = 42; sm.column_dimensions["B"].width = 20
    sm.conditional_formatting.add("B7", CellIsRule(operator="greaterThan", formula=["0.2"], fill=RED))
    wb.save(path)
    return Path(path)
